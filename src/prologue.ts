import type { Companion, Effects, GodId, RunState } from './types'

export interface PrologueOption {
  id: string
  title: string
  description: string
  effects: Effects
  /** Изменение рока: клятвы и память войны ложатся на плечи. */
  doom: number
  logTitle: string
  logText: string
}

export interface Prologue {
  id: string
  title: string
  subtitle: string
  text: string
  quote: string
  options: PrologueOption[]
}

/** Вариант сцены-знамения (глашатай Посейдона, порог Итаки). */
export interface InterludeOption {
  id: string
  title: string
  description: string
  effects: Effects
  doom: number
  gods?: Partial<Record<GodId, number>>
  coins?: number
  logTitle: string
  logText: string
}

export interface InterludeScene {
  id: string
  title: string
  subtitle: string
  text: string
  quote: string
  options: InterludeOption[]
}

