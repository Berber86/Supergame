function pairKey(companions: Companion[]) {
  return companions.map((companion) => companion.id).sort().join('+')
}

/** Возвращает пролог для пары стартовых спутников. */
export function prologueFor(companions: Companion[]): Prologue {
  return prologues[pairKey(companions)] ?? prologues['eurylochus+tiphys']
}

