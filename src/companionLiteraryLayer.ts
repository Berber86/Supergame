export function companionLiteraryLayer(encounterId: string, success: boolean) {
  const layer = layers[encounterId]
  if (!layer) return undefined
  return success
    ? { aftermath: layer.success, crewVoice: layer.crewSuccess, consequence: layer.consequenceSuccess }
    : { aftermath: layer.failure, crewVoice: layer.crewFailure, consequence: layer.consequenceFailure }
}
